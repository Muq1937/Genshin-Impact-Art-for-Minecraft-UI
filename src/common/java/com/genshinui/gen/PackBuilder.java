package com.genshinui.gen;

import com.genshinui.theme.Theme;
import com.genshinui.theme.UiTarget;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.function.IntFunction;
import java.util.stream.Stream;

import static com.genshinui.gen.Compositor.IconPart.*;

/** Writes a complete resource pack for a theme. Pure Java; safe to run off the render thread. */
public final class PackBuilder {
    /** Bump when generation output changes so existing packs get rebuilt. */
    public static final int GEN_VERSION = 8;
    /** Book-open screen variants: assets/genshinui/textures/gui/book_open/<vanilla path under textures/gui>.png */
    public static final String BOOK_OPEN_DIR = "assets/genshinui/textures/gui/book_open/";

    private static final String GUI = "assets/minecraft/textures/gui/";
    private static final String SPR = GUI + "sprites/";

    private final Theme theme;
    private final VanillaSource vanilla;
    private final Compositor cx;
    private final Path out;

    public PackBuilder(Theme theme, VanillaSource vanilla, int scale, IntFunction<BufferedImage> images, Path out) {
        this.theme = theme;
        this.vanilla = vanilla;
        this.cx = new Compositor(theme, scale, images);
        this.out = out;
    }

    public Compositor compositor() {
        return cx;
    }

    /** Minecraft 1.21.8 and older: a single integer pack format. */
    public void build(int packFormat, String stamp) throws IOException {
        build("\"pack_format\": " + packFormat, stamp);
    }

    /** Minecraft 1.21.9 and newer (incl. 26.x): major.minor pack versions, declared as a supported range. */
    public void build(int major, int minor, String stamp) throws IOException {
        build("\"min_format\": [" + major + ", " + minor + "],\n    \"max_format\": [" + major + ", " + minor + "]", stamp);
    }

    private void build(String formatFields, String stamp) throws IOException {
        if (Files.exists(out)) deleteTree(out);
        Files.createDirectories(out);

        String desc = "§d" + theme.name + (theme.character.isBlank() ? "" : " §7(" + theme.character + ")") + "\n§8Generated by Genshin UI Themes";
        String mcmeta = "{\n  \"pack\": {\n    " + formatFields + ",\n    \"description\": " + jsonString(desc) + "\n  }\n}\n";
        writeText("pack.mcmeta", mcmeta);
        writeText("genshinui_stamp.txt", stamp);
        png("pack.png", cx.packIcon());

        // containers
        for (UiTarget t : UiTarget.values()) {
            if (t.kind != UiTarget.Kind.CONTAINER) continue;
            for (String name : t.textures) {
                String path = "textures/gui/" + name + ".png";
                BufferedImage van = vanilla.image(path);
                if (van == null) continue;
                String outPath = t.customOutput() != null ? t.customOutput() : "assets/minecraft/" + path;
                png(outPath, cx.container(van, t));
            }
        }

        // screens with a connected recipe book: extra variant used while the book is open
        // (RecipeBookScreenMixin swaps to it), so the book-closed screen keeps its own image
        for (UiTarget book : new UiTarget[]{UiTarget.RECIPE_BOOK, UiTarget.RECIPE_BOOK_CRAFTING, UiTarget.RECIPE_BOOK_FURNACE}) {
            if (!theme.isConnected(book)) continue;
            UiTarget host = book.recipeHost();
            for (String name : host.textures) {
                BufferedImage van = vanilla.image("textures/gui/" + name + ".png");
                if (van != null) png(BOOK_OPEN_DIR + name + ".png", cx.container(van, host, book));
            }
        }

        // seamless chests per row count (drawn by GenericContainerScreenMixin instead of vanilla's two slices)
        BufferedImage generic54 = vanilla.image("textures/gui/container/generic_54.png");
        if (generic54 != null) {
            for (int rows = 1; rows <= 6; rows++) {
                png("assets/genshinui/textures/gui/chest_" + rows + ".png",
                        cx.container(Compositor.stitchChest(generic54, rows), UiTarget.CHEST));
            }
        }

        // hotbar + xp
        png(SPR + "hud/hotbar.png", cx.hotbar());
        png(SPR + "hud/hotbar_selection.png", cx.hotbarSelection());
        for (String side : new String[]{"left", "right"}) {
            BufferedImage van = vanilla.image("textures/gui/sprites/hud/hotbar_offhand_" + side + ".png");
            if (van != null) png(SPR + "hud/hotbar_offhand_" + side + ".png", cx.offhand(van));
        }
        png(SPR + "hud/experience_bar_background.png", cx.xpBackground());
        png(SPR + "hud/experience_bar_progress.png", cx.xpProgress());

        // hearts
        int heart = cx.p.heart;
        int blink = com.genshinui.theme.Colors2.lighter(heart, 0.55);
        for (String pre : new String[]{"", "hardcore_"}) {
            png(SPR + "hud/heart/" + pre + "full.png", cx.icon("heart", FULL, heart));
            png(SPR + "hud/heart/" + pre + "half.png", cx.icon("heart", HALF_LEFT, heart));
            png(SPR + "hud/heart/" + pre + "full_blinking.png", cx.icon("heart", FULL, blink));
            png(SPR + "hud/heart/" + pre + "half_blinking.png", cx.icon("heart", HALF_LEFT, blink));
        }
        png(SPR + "hud/heart/container.png", cx.icon("heart", CONTAINER, 0));
        png(SPR + "hud/heart/container_hardcore.png", cx.icon("heart", CONTAINER, 0));
        png(SPR + "hud/heart/container_blinking.png", cx.icon("heart", CONTAINER_BLINK, 0));
        png(SPR + "hud/heart/container_hardcore_blinking.png", cx.icon("heart", CONTAINER_BLINK, 0));

        // hunger icons (themed shape)
        String shape = theme.icons;
        int food = com.genshinui.theme.Colors2.mixRgb(cx.p.accent, cx.p.lightC, 0.2);
        int hunger = com.genshinui.theme.Colors2.mixRgb(food, 0xFF7FA03A, 0.7);
        png(SPR + "hud/food_empty.png", cx.icon(shape, CONTAINER, 0));
        png(SPR + "hud/food_full.png", cx.icon(shape, FULL, food));
        png(SPR + "hud/food_half.png", cx.icon(shape, HALF_RIGHT, food));
        png(SPR + "hud/food_empty_hunger.png", cx.icon(shape, CONTAINER, 0));
        png(SPR + "hud/food_full_hunger.png", cx.icon(shape, FULL, hunger));
        png(SPR + "hud/food_half_hunger.png", cx.icon(shape, HALF_RIGHT, hunger));

        // armor: tint vanilla pixel art
        for (String a : new String[]{"armor_full", "armor_half"}) {
            BufferedImage van = vanilla.image("textures/gui/sprites/hud/" + a + ".png");
            if (van != null) png(SPR + "hud/" + a + ".png", cx.tint(van, cx.p.accent));
        }

        // widgets (+ copy vanilla nine-slice metadata so scaling stays identical)
        sprite("widget/button", cx.button(0));
        sprite("widget/button_highlighted", cx.button(1));
        sprite("widget/button_disabled", cx.button(2));
        sprite("widget/text_field", cx.field(false, false));
        sprite("widget/text_field_highlighted", cx.field(true, false));
        sprite("widget/slider", cx.field(false, true));
        sprite("widget/slider_highlighted", cx.field(true, true));
        sprite("widget/slider_handle", cx.sliderHandle(false));
        sprite("widget/slider_handle_highlighted", cx.sliderHandle(true));
        sprite("tooltip/background", cx.tooltipBackground());
        sprite("tooltip/frame", cx.tooltipFrame());

        // mod-owned textures
        png("assets/genshinui/textures/gui/menu_art.png", cx.menuArt());
        png("assets/genshinui/textures/gui/particle.png", cx.particleSprite());

        // recipe book + creative tabs: small sprites recolored by vanilla palette
        for (String name : RECOLOR_SPRITES) {
            BufferedImage van = vanilla.image("textures/gui/sprites/" + name + ".png");
            if (van != null) sprite(name, cx.recolorSprite(van));
        }
    }

    private static final List<String> RECOLOR_SPRITES = buildSpriteList();

    private static List<String> buildSpriteList() {
        List<String> l = new ArrayList<>();
        for (String s : new String[]{"tab", "tab_selected", "slot_craftable", "slot_many_craftable", "slot_uncraftable",
                "slot_many_uncraftable", "page_forward", "page_forward_highlighted", "page_backward", "page_backward_highlighted",
                "button", "button_highlighted", "overlay_recipe", "crafting_overlay", "crafting_overlay_highlighted",
                "crafting_overlay_disabled", "crafting_overlay_disabled_highlighted", "furnace_overlay", "furnace_overlay_highlighted",
                "furnace_overlay_disabled", "furnace_overlay_disabled_highlighted", "filter_enabled", "filter_enabled_highlighted",
                "filter_disabled", "filter_disabled_highlighted", "furnace_filter_enabled", "furnace_filter_enabled_highlighted",
                "furnace_filter_disabled", "furnace_filter_disabled_highlighted"}) {
            l.add("recipe_book/" + s);
        }
        for (String pos : new String[]{"top", "bottom"})
            for (String st : new String[]{"selected", "unselected"})
                for (int i = 1; i <= 7; i++) l.add("container/creative_inventory/tab_" + pos + "_" + st + "_" + i);
        return l;
    }

    private void sprite(String name, BufferedImage img) throws IOException {
        png(SPR + name + ".png", img);
        String meta = vanilla.text("textures/gui/sprites/" + name + ".png.mcmeta");
        if (meta != null) writeText(SPR + name + ".png.mcmeta", meta);
    }

    private void png(String rel, BufferedImage img) throws IOException {
        Path f = out.resolve(rel);
        Files.createDirectories(f.getParent());
        ImageIO.write(img, "png", f.toFile());
    }

    private void writeText(String rel, String s) throws IOException {
        Path f = out.resolve(rel);
        Files.createDirectories(f.getParent());
        Files.writeString(f, s, StandardCharsets.UTF_8);
    }

    static String jsonString(String s) {
        StringBuilder b = new StringBuilder("\"");
        for (char ch : s.toCharArray()) {
            switch (ch) {
                case '"' -> b.append("\\\"");
                case '\\' -> b.append("\\\\");
                case '\n' -> b.append("\\n");
                default -> {
                    if (ch < 0x20 || ch > 0x7e) b.append(String.format("\\u%04x", (int) ch));
                    else b.append(ch);
                }
            }
        }
        return b.append('"').toString();
    }

    public static void deleteTree(Path p) throws IOException {
        try (Stream<Path> s = Files.walk(p)) {
            for (Path x : s.sorted(Comparator.reverseOrder()).toList()) Files.deleteIfExists(x);
        }
    }
}
